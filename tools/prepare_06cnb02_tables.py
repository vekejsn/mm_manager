"""Build a size-checked 06CNB02 lab profile, preserving all source tables."""
import argparse
import hashlib
import json
import struct
from pathlib import Path

SHA256 = '540af81948ea009c7efbd424fe67ef29e24304ec9bdb0b4a4fc6485126fe9e99'


def packed(number, length, zero_digit=10):
    if not number.isascii() or not number.isdigit() or len(number) > length*2:
        raise ValueError('Invalid number or field length')
    digits = [int(c) or zero_digit for c in number] + [0]*(length*2-len(number))
    return bytes((digits[i]<<4)|digits[i+1] for i in range(0,len(digits),2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rom',required=True,type=Path)
    parser.add_argument('--output',required=True,type=Path)
    parser.add_argument('--terminal-id',default='1234567890')
    parser.add_argument('--number',default='1234')
    parser.add_argument('--selector',type=int,default=25)
    args = parser.parse_args()
    rom = args.rom.read_bytes()
    if hashlib.sha256(rom).hexdigest() != SHA256:
        parser.error('Expected exact original 06CNB02 ROM')
    if args.output.exists(): parser.error('Use a new output directory')
    if not 1 <= args.selector <= 32: parser.error('Selector must be 1..32')
    if len(args.terminal_id) != 10 or not 1 <= len(args.number) <= 12:
        parser.error('Terminal ID needs 10 digits; management number needs 1..12')
    root = Path(__file__).resolve().parents[1]
    entries = {}
    for offset in range(0x33C0,0x3640,10):
        typ,action,size,ram,default_size,default_ptr = struct.unpack_from('<BBHHHH',rom,offset)
        if action in (0x47,0x48,0x49,0x4A) and typ not in entries:
            entries[typ] = (size,rom[default_ptr:default_ptr+default_size])
    assert len(entries) == 27
    args.output.mkdir()
    manifest = dict(rom_sha256=SHA256,terminal_id=args.terminal_id,number=args.number,
                    selector=args.selector,tables=[])
    for typ,(size,default) in entries.items():
        name = f'mm_table_{typ:02x}.bin'
        data, source = None,None
        for folder in ('PTT_BIH_DUMP/converted','default'):
            candidate = root/'tables'/folder/name
            if candidate.exists() and candidate.stat().st_size == size-1:
                data,source = candidate.read_bytes(),str(candidate.relative_to(root))
                break
        if data is None:
            assert not default or default[0] == typ
            data = (default[1:] if default else b'').ljust(size-1,b'\0')
            source = 'ROM default, zero-extended to declared payload size'
        data = bytearray(data)
        if typ == 21:
            data[:] = packed(args.terminal_id,5,zero_digit=0)+packed(args.number,6)+bytes(6)
            source = 'Lab identity and NCC access number (also generated by manager)'
        elif typ == 31:
            data[:] = (default[1:] if default else b'').ljust(36,b'\0')
            data[32:36] = bytes(4)
            data[32+(args.selector-1)//8] |= 1 << (7-(args.selector-1)%8)
            source = 'ROM installation defaults plus explicit TTY selector bitmap'
        elif typ == 55:
            for slot,mode,flag in ((0,4,0x20),(1,1,0x10)):
                base=slot*57
                data[base+3:base+11] = packed(args.number,8)
                data[base+11:base+31] = b'ONLINE SERVICES'.ljust(20)
                data[base+31:base+51] = b'CONNECTING'.ljust(20)
                data[base+51] = mode
                data[base+55] = flag
            source += '; slots 0/1 configured for patched **nn/*** TTY'
        assert len(data) == size-1,(typ,len(data),size)
        (args.output/name).write_bytes(data)
        manifest['tables'].append(dict(id=typ,file=name,bytes=len(data),source=source,
                                      sha256=hashlib.sha256(data).hexdigest()))
    (args.output/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Prepared {len(entries)} target-sized tables in {args.output}')


if __name__ == '__main__': main()
